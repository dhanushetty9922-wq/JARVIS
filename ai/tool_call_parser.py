"""JARVIS Tool Call Parser & Schema Validator (Phase 4).

Safely extracts, parses, sanitizes, and validates AI tool plans against
the central ToolRegistry before any execution attempt.

CRITICAL SECURITY RULES:
- AI output is treated as UNTRUSTED.
- Rejects any tool not explicitly registered in ToolRegistry.
- Rejects arbitrary shell commands (powershell, cmd, bash, exec, run_command).
- Validates arguments against the tool's strongly-typed Pydantic input_schema.
- Never directly executes anything — returns validated ToolCallRequest objects.
"""

from __future__ import annotations

import json
import logging
import re
from typing import Any, Dict, List, Optional, Tuple
from pydantic import ValidationError

from ai.provider import AIResult, ToolCallRequest
from tools.registry import ToolRegistry

logger = logging.getLogger("jarvis.ai.parser")

# Dangerous command tokens that must NEVER appear in tool arguments or invented tools
DANGEROUS_TOKENS = [
    "powershell",
    "powershell.exe",
    "cmd.exe",
    "cmd /c",
    "bash",
    "sh -c",
    "wscript",
    "cscript",
    "certutil",
    "bitsadmin",
    "format c:",
    "rmdir /s",
    "del /f /s /q",
]


class ToolCallParser:
    """Parses and validates structured tool calls generated by AI providers."""

    def __init__(self, registry: ToolRegistry):
        self.registry = registry

    def parse_raw_response(self, raw_text: str, provider_name: str = "", model_name: str = "") -> AIResult:
        """Parse raw LLM text response into validated AIResult."""
        if not raw_text or not raw_text.strip():
            return AIResult.conversational("I did not receive a response.", provider=provider_name, model=model_name)

        trimmed = raw_text.strip()

        # 1. Attempt to extract JSON from markdown code block ```json ... ``` or ``` ... ```
        json_obj = self._extract_json(trimmed)
        if json_obj is not None:
            return self._process_json_payload(json_obj, trimmed, provider_name, model_name)

        # 2. If no JSON structure found, check if plain text response is a truncated JSON message
        if trimmed.startswith("{") and ('"message"' in trimmed or "'message'" in trimmed):
            msg_match = re.search(r'["\']message["\']\s*:\s*["\'](.*?)(?:["\']\s*\}|\s*$)', trimmed, re.DOTALL)
            if msg_match:
                extracted = msg_match.group(1)
                extracted = extracted.replace('\\n', '\n').replace('\\"', '"').replace('\\\\', '\\')
                return AIResult.conversational(extracted.strip(), provider=provider_name, model=model_name)

        return AIResult.conversational(trimmed, provider=provider_name, model=model_name)

    def _extract_json(self, text: str) -> Optional[Dict[str, Any]]:
        """Extract and parse first valid JSON object from text."""
        # Check fenced code block
        code_block_match = re.search(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.DOTALL)
        if code_block_match:
            try:
                return json.loads(code_block_match.group(1))
            except json.JSONDecodeError:
                pass

        # Check raw json object in text
        json_match = re.search(r"(\{.*\})", text, re.DOTALL)
        if json_match:
            try:
                return json.loads(json_match.group(1))
            except json.JSONDecodeError:
                pass

        return None

    def _process_json_payload(
        self,
        payload: Dict[str, Any],
        raw_text: str,
        provider_name: str,
        model_name: str,
    ) -> AIResult:
        """Process structured JSON payload into validated AIResult."""
        # Format 1: Clarification question
        req_type = str(payload.get("type", "")).lower()
        if req_type == "clarification" or "question" in payload:
            question = payload.get("question") or payload.get("message") or "Could you clarify your request?"
            return AIResult.clarification(str(question), provider=provider_name, model=model_name)

        # Format 2: Pure conversational response
        if req_type == "response" or (req_type == "message" and "tool" not in payload and "tool_call" not in payload):
            message = payload.get("message") or payload.get("content") or "Ready."
            return AIResult.conversational(str(message), provider=provider_name, model=model_name)

        # Format 3: Tool Call {"type": "tool_call", "tool": "...", "arguments": {...}}
        # Or {"tool": "...", "arguments": {...}}
        tool_name = payload.get("tool") or payload.get("tool_name") or payload.get("name")
        arguments = payload.get("arguments") or payload.get("parameters") or payload.get("args") or {}

        if tool_name:
            validated_call, err = self.validate_tool_call(str(tool_name), arguments)
            if err:
                logger.warning(f"Tool call validation rejected: {err}")
                return AIResult.fail(err, provider=provider_name, model=model_name)
            return AIResult(
                tool_calls=[validated_call],
                raw_response=raw_text,
                provider_name=provider_name,
                model_name=model_name,
            )

        # Fallback to conversational if JSON didn't specify known tool
        return AIResult.conversational(raw_text, provider=provider_name, model=model_name)

    def validate_tool_call(self, tool_name: str, arguments: Any) -> Tuple[Optional[ToolCallRequest], Optional[str]]:
        """Validate proposed tool call against ToolRegistry and security policies.
        
        Returns:
            Tuple of (Validated ToolCallRequest or None, Error message or None)
        """
        clean_name = str(tool_name).strip().lower()

        # Step 1: Check for arbitrary shell injection in tool name
        for token in DANGEROUS_TOKENS:
            if token in clean_name:
                return None, f"Security Violation: Proposed tool '{tool_name}' contains dangerous shell token '{token}'. Direct shell execution is strictly forbidden."

        # Step 2: Verify tool exists in central registry
        tool = self.registry.get(clean_name)
        if not tool:
            available = [t.name for t in self.registry.list_tools()]
            return None, f"Tool '{tool_name}' is not an approved JARVIS tool. Approved tools: {', '.join(available)}"

        # Step 3: Ensure arguments is a dictionary
        if not isinstance(arguments, dict):
            if arguments is None:
                arguments = {}
            else:
                return None, f"Invalid arguments format for tool '{clean_name}'. Expected dictionary, got {type(arguments).__name__}."

        # Step 4: Check for shell command injection within argument values
        for k, v in arguments.items():
            str_v = str(v).lower()
            for token in DANGEROUS_TOKENS:
                if token in str_v:
                    return None, f"Security Violation: Argument '{k}' contains prohibited command execution token '{token}'."

        # Step 5: Strongly validate arguments against tool's Pydantic input_schema
        try:
            validated_model = tool.input_schema(**arguments)
            # Use validated dump to ensure types and defaults are canonical
            sanitized_args = validated_model.model_dump()
        except ValidationError as e:
            errors = [f"{err['loc']}: {err['msg']}" for err in e.errors()]
            return None, f"Argument validation failed for tool '{clean_name}': {'; '.join(errors)}"
        except Exception as e:
            return None, f"Unexpected argument error for tool '{clean_name}': {e}"

        return ToolCallRequest(tool_name=tool.name, arguments=sanitized_args), None
