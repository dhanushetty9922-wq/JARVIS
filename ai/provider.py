"""JARVIS AI Provider Interface & Abstractions (Phase 4).

Defines the contract for local, cloud, and hybrid AI providers.
Ensures uniform output structures regardless of whether inference
happens locally or via OpenRouter.

CRITICAL ARCHITECTURE:
- Providers ONLY generate structured plans or text responses.
- Providers NEVER execute tools or interact with the OS directly.
"""

from __future__ import annotations

import logging
from abc import ABC, abstractmethod
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field

logger = logging.getLogger("jarvis.ai.provider")


class ToolCallRequest(BaseModel):
    """Structured tool invocation request generated by AI."""
    tool_name: str = Field(description="Name of the registered tool to execute.")
    arguments: Dict[str, Any] = Field(default_factory=dict, description="Validated keyword arguments for the tool.")
    call_id: Optional[str] = Field(default=None, description="Optional call identifier from LLM.")


class AIResult(BaseModel):
    """Standardized output from any AI provider."""
    content: Optional[str] = Field(default=None, description="Conversational or clarification message from AI.")
    tool_calls: List[ToolCallRequest] = Field(default_factory=list, description="List of proposed tool calls.")
    is_conversational: bool = Field(default=False, description="True if response is purely conversational.")
    clarification_needed: bool = Field(default=False, description="True if user request was ambiguous.")
    raw_response: Optional[str] = Field(default=None, description="Raw text response from the model.")
    error: Optional[str] = Field(default=None, description="Error message if generation failed.")
    provider_name: str = Field(default="", description="Name of provider that generated this result.")
    model_name: str = Field(default="", description="Name of model used.")

    @property
    def has_tool_calls(self) -> bool:
        return len(self.tool_calls) > 0

    @classmethod
    def tool_call(cls, tool_name: str, arguments: Dict[str, Any], provider: str = "", model: str = "") -> AIResult:
        return cls(
            tool_calls=[ToolCallRequest(tool_name=tool_name, arguments=arguments)],
            provider_name=provider,
            model_name=model,
        )

    @classmethod
    def conversational(cls, message: str, provider: str = "", model: str = "") -> AIResult:
        return cls(
            content=message,
            is_conversational=True,
            provider_name=provider,
            model_name=model,
        )

    @classmethod
    def clarification(cls, question: str, provider: str = "", model: str = "") -> AIResult:
        return cls(
            content=question,
            clarification_needed=True,
            provider_name=provider,
            model_name=model,
        )

    @classmethod
    def fail(cls, error_msg: str, provider: str = "", model: str = "") -> AIResult:
        return cls(
            error=error_msg,
            content=error_msg,
            provider_name=provider,
            model_name=model,
        )


class BaseAIProvider(ABC):
    """Abstract base class for all JARVIS AI providers."""

    name: str

    @abstractmethod
    def is_available(self) -> bool:
        """Check if provider endpoint and model are reachable and ready."""
        pass

    @abstractmethod
    async def generate_response(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        tools: Optional[List[Dict[str, Any]]] = None,
    ) -> AIResult:
        """Generate response or tool plan from natural language prompt."""
        pass

    @abstractmethod
    def get_model_info(self) -> Dict[str, Any]:
        """Return diagnostic metadata about current model configuration."""
        pass
